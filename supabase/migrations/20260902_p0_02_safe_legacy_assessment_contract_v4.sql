  session_id bigint not null references public.practice_sessions_v4(id) on delete cascade,
  question_id bigint not null references public.questions(id),
  user_answer text,
  picked_index integer,
  is_correct boolean not null,
  time_spent integer not null default 0 check (time_spent >= 0),
  answered_at timestamptz not null default now(),
  primary key (session_id, question_id)
);

create table if not exists public.tour_session_runtime_v4 (
  attempt_id bigint primary key references public.tour_attempts(id) on delete cascade,
  user_id uuid not null,
  tour_id bigint not null references public.tours(id),
  client_session_id text not null,
  question_ids bigint[] not null,
  finalized_at timestamptz,
  created_at timestamptz not null default now(),
  unique (user_id, client_session_id),
  unique (user_id, tour_id),
  check (cardinality(question_ids) = 20),
  check (length(client_session_id) between 8 and 128)
);

create table if not exists public.tour_session_answers_v4 (
  attempt_id bigint not null references public.tour_session_runtime_v4(attempt_id) on delete cascade,
  question_id bigint not null references public.questions(id),
  user_answer text,
  answered boolean not null default true,
  is_correct boolean not null default false,
  time_spent integer not null default 0 check (time_spent >= 0),
  finish_reason text,
  answered_at timestamptz not null default now(),
  primary key (attempt_id, question_id)
);

