  id bigint generated by default as identity primary key,
  user_id uuid not null,
  subject_id bigint not null references public.subjects(id),
  pool_id bigint not null references public.practice_pools(id),
  client_session_id text not null,
  question_ids bigint[] not null,
  legacy_attempt_id bigint unique references public.practice_attempts(id),
  status text not null default 'in_progress'
    check (status in ('in_progress','finalized','abandoned')),
  created_at timestamptz not null default now(),
  finalized_at timestamptz,
  unique (user_id, client_session_id),
  check (cardinality(question_ids) = 10),
  check (length(client_session_id) between 8 and 128)
);

