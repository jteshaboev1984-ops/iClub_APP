create or replace function public.submit_practice_session_answer_safe_v2(
  p_session_id bigint,
  p_question_id bigint,
  p_user_answer text,
  p_picked_index integer,
  p_time_spent integer
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_s public.practice_sessions_v2%rowtype;
  v_q public.questions%rowtype;
  v_eval jsonb;
  v_answered integer;
  v_score integer;
begin
  if v_uid is null then
    raise exception 'not_authenticated' using errcode = '28000';
  end if;

  select * into v_s from public.practice_sessions_v2 s
  where s.id = p_session_id and s.user_id = v_uid;

  if v_s.id is null then
    raise exception 'session_not_found' using errcode = 'P0002';
  end if;
  if v_s.status <> 'in_progress' then
    raise exception 'session_not_in_progress' using errcode = '55000';
  end if;
  if not (p_question_id = any(v_s.question_ids)) then
    raise exception 'question_not_in_session' using errcode = '22023';
  end if;

  select q.* into v_q from public.questions q
  where q.id = p_question_id and q.is_active is true and q.subject_id = v_s.subject_id;
  if v_q.id is null then
    raise exception 'question_not_found_or_subject_mismatch' using errcode = 'P0002';
  end if;

  v_eval := public.iclub_practice_eval_v2(p_question_id,p_user_answer,p_picked_index);

  insert into public.practice_session_answers_v2(
    session_id, question_id, selected_answer, picked_index, is_correct, time_spent,
    diagnostic_id, mistake_type, weak_skill, feedback_ru, feedback_uz, feedback_en,
    next_action_ru, next_action_uz, next_action_en, answered_at
  ) values (
    p_session_id, p_question_id,
    v_eval->>'selected_answer', p_picked_index, coalesce((v_eval->>'is_correct')::boolean,false),
    greatest(coalesce(p_time_spent,0),0),
    nullif(v_eval->>'diagnostic_id','')::bigint,
    v_eval->>'mistake_type', v_eval->>'weak_skill',
    v_eval->>'feedback_ru', v_eval->>'feedback_uz', v_eval->>'feedback_en',
    v_eval->>'next_action_ru', v_eval->>'next_action_uz', v_eval->>'next_action_en', now()
  )
  on conflict (session_id,question_id) do update set
    selected_answer = excluded.selected_answer,
    picked_index = excluded.picked_index,
    is_correct = excluded.is_correct,
    time_spent = excluded.time_spent,
    diagnostic_id = excluded.diagnostic_id,
    mistake_type = excluded.mistake_type,
    weak_skill = excluded.weak_skill,
    feedback_ru = excluded.feedback_ru,
    feedback_uz = excluded.feedback_uz,
    feedback_en = excluded.feedback_en,
    next_action_ru = excluded.next_action_ru,
    next_action_uz = excluded.next_action_uz,
    next_action_en = excluded.next_action_en,
    answered_at = now();

  select count(*)::integer,
         count(*) filter (where a.is_correct is true)::integer
    into v_answered, v_score
  from public.practice_session_answers_v2 a
  where a.session_id = p_session_id;

  -- Practice is a learning flow: reveal only THIS answered question after server acceptance.
  -- No future question answer key is returned.
  return jsonb_build_object(
    'ok', true,
    'session_id', p_session_id,
    'question_id', p_question_id,
    'is_correct', coalesce((v_eval->>'is_correct')::boolean,false),
    'answered', v_answered,
    'score_so_far', v_score,
    'question_count', cardinality(v_s.question_ids),
    'correct_answer', v_q.correct_answer,
    'explanation', v_q.explanation,
    'explanation_ru', v_q.explanation_ru,
    'explanation_uz', v_q.explanation_uz,
    'explanation_en', v_q.explanation_en,
    'diagnostic_id', nullif(v_eval->>'diagnostic_id','')::bigint,
    'mistake_type', v_eval->>'mistake_type',
    'weak_skill', v_eval->>'weak_skill',
    'feedback_ru', v_eval->>'feedback_ru',
    'feedback_uz', v_eval->>'feedback_uz',
    'feedback_en', v_eval->>'feedback_en',
    'next_action_ru', v_eval->>'next_action_ru',
    'next_action_uz', v_eval->>'next_action_uz',
    'next_action_en', v_eval->>'next_action_en'
  );
end;
$$;

create or replace function public.finalize_practice_session_safe_v2(
  p_session_id bigint,
  p_total_time integer
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_s public.practice_sessions_v2%rowtype;
  v_answered integer;
  v_score integer;
  v_percent numeric;
  v_attempt_id bigint;
  v_row public.practice_session_answers_v2%rowtype;
  v_practice_answer_id bigint;
begin
  if v_uid is null then
    raise exception 'not_authenticated' using errcode = '28000';
  end if;

  select * into v_s from public.practice_sessions_v2 s
  where s.id = p_session_id and s.user_id = v_uid
  for update;

  if v_s.id is null then
    raise exception 'session_not_found' using errcode = 'P0002';
  end if;

  if v_s.status = 'finalized' and v_s.legacy_attempt_id is not null then
    select pa.score, pa.percent into v_score, v_percent
    from public.practice_attempts pa where pa.id = v_s.legacy_attempt_id;
    return jsonb_build_object(
      'ok', true, 'session_id', v_s.id, 'attempt_id', v_s.legacy_attempt_id,
      'score', coalesce(v_score,0), 'percent', coalesce(v_percent,0),
      'question_count', cardinality(v_s.question_ids), 'idempotent', true
    );
  end if;

  if v_s.status <> 'in_progress' then
    raise exception 'session_not_in_progress' using errcode = '55000';
  end if;

  select count(*)::integer,
         count(*) filter (where a.is_correct is true)::integer
    into v_answered, v_score
  from public.practice_session_answers_v2 a
  where a.session_id = p_session_id
    and a.question_id = any(v_s.question_ids);

  if v_answered <> cardinality(v_s.question_ids) then
    raise exception 'session_answers_incomplete' using errcode = '55000';
  end if;

  v_percent := case when v_answered > 0
    then round((v_score::numeric / v_answered::numeric) * 100, 2)
    else 0 end;

  insert into public.practice_attempts(user_id,subject_id,score,percent,time_seconds)
  values (v_uid,v_s.subject_id,v_score,v_percent,greatest(coalesce(p_total_time,0),0))
  returning id into v_attempt_id;

  for v_row in
    select a.* from public.practice_session_answers_v2 a
    cross join lateral (
      select min(x.ord) as ord
      from unnest(v_s.question_ids) with ordinality x(qid,ord)
      where x.qid = a.question_id
    ) o
    where a.session_id = p_session_id
    order by o.ord
  loop
    insert into public.practice_answers(attempt_id,question_id,user_answer,is_correct,time_spent)
    values (v_attempt_id,v_row.question_id,v_row.selected_answer,v_row.is_correct,v_row.time_spent)
    returning id into v_practice_answer_id;

    insert into public.user_answer_diagnosis(
      user_id,subject_id,attempt_type,attempt_id,practice_answer_id,question_id,
      selected_answer,is_correct,diagnostic_id,mistake_type,weak_skill,
      feedback_ru,feedback_uz,feedback_en,next_action_ru,next_action_uz,next_action_en
    ) values (
      v_uid,v_s.subject_id,'practice',v_attempt_id,v_practice_answer_id,v_row.question_id,
      v_row.selected_answer,v_row.is_correct,v_row.diagnostic_id,v_row.mistake_type,v_row.weak_skill,
      v_row.feedback_ru,v_row.feedback_uz,v_row.feedback_en,
      v_row.next_action_ru,v_row.next_action_uz,v_row.next_action_en
    )
    on conflict (practice_answer_id) where practice_answer_id is not null
    do update set
      selected_answer=excluded.selected_answer,
      is_correct=excluded.is_correct,
      diagnostic_id=excluded.diagnostic_id,
      mistake_type=excluded.mistake_type,
      weak_skill=excluded.weak_skill,
      feedback_ru=excluded.feedback_ru,
      feedback_uz=excluded.feedback_uz,
      feedback_en=excluded.feedback_en,
      next_action_ru=excluded.next_action_ru,
      next_action_uz=excluded.next_action_uz,
      next_action_en=excluded.next_action_en;
  end loop;

  update public.practice_sessions_v2
  set status='finalized', legacy_attempt_id=v_attempt_id, finalized_at=now()
  where id=p_session_id and user_id=v_uid;

  return jsonb_build_object(
    'ok', true, 'session_id', p_session_id, 'attempt_id', v_attempt_id,
    'score', v_score, 'percent', v_percent,
    'question_count', v_answered, 'idempotent', false
  );
end;
$$;

