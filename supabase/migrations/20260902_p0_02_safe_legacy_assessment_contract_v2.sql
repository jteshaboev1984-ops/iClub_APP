create or replace function public.iclub_tour_input_is_correct_v2(
  p_user_answer text,
  p_expected_answer text
)
returns boolean
language plpgsql
immutable
set search_path = public, pg_temp
as $$
declare
  v_user text := trim(translate(coalesce(p_user_answer,''), '−–—', '---'));
  v_expected text := trim(translate(coalesce(p_expected_answer,''), '−–—', '---'));
  v_user_num double precision;
  v_expected_num double precision;
  v_diff double precision;
  v_scale double precision;
  v_expected_signed boolean;
begin
  if v_user = '' or v_expected = '' then
    return false;
  end if;

  -- Mirrors current Tour client strict numeric format:
  -- dot decimal, optional explicit sign, optional e/E notation, no internal spaces/units.
  if v_expected ~ '^[+-]?[0-9]+([.][0-9]+)?([eE][+-]?[0-9]+)?$' then
    if v_user !~ '^[+-]?[0-9]+([.][0-9]+)?([eE][+-]?[0-9]+)?$' then
      return false;
    end if;

    v_expected_signed := v_expected ~ '^[+-]';
    if v_expected_signed then
      if left(v_expected,1) <> left(v_user,1) then
        return false;
      end if;
    elsif v_user ~ '^[+-]' then
      return false;
    end if;

    begin
      v_user_num := v_user::double precision;
      v_expected_num := v_expected::double precision;
    exception when others then
      return false;
    end;

    v_diff := abs(v_user_num - v_expected_num);
    v_scale := greatest(1::double precision, abs(v_user_num), abs(v_expected_num));
    return v_diff <= v_scale * 1e-9;
  end if;

  -- Formula/token mode used by current client: ASCII alphanumeric only,
  -- case-insensitive, no spaces/subscript glyphs.
  if v_expected ~ '^[A-Z][A-Za-z0-9]*$' then
    if v_user !~ '^[A-Za-z][A-Za-z0-9]*$' then
      return false;
    end if;
    return lower(v_user) = lower(v_expected);
  end if;

  -- Current free-text fallback removes whitespace and compares case-insensitively.
  return lower(regexp_replace(v_user, '\s+', '', 'g'))
       = lower(regexp_replace(v_expected, '\s+', '', 'g'));
end;
$$;

create or replace function public.iclub_practice_eval_v2(
  p_question_id bigint,
  p_user_answer text,
  p_picked_index integer
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_q public.questions%rowtype;
  v_diag public.question_answer_diagnostics%rowtype;
  v_selected text;
  v_selected_norm text;
  v_is_correct boolean := false;
begin
  select q.* into v_q
  from public.questions q
  where q.id = p_question_id
    and q.is_active is true;

  if v_q.id is null then
    raise exception 'question_not_found_or_inactive' using errcode = 'P0002';
  end if;

  if lower(coalesce(v_q.qtype,'')) = 'mcq' then
    if p_picked_index is not null and p_picked_index between 0 and 25 then
      v_selected := chr(65 + p_picked_index);
    elsif trim(coalesce(p_user_answer,'')) ~ '^[0-9]+$'
      and trim(p_user_answer)::integer between 0 and 25 then
      v_selected := chr(65 + trim(p_user_answer)::integer);
    else
      v_selected := upper(trim(coalesce(p_user_answer,'')));
    end if;

    v_is_correct := (
      upper(trim(coalesce(v_selected,''))) = upper(trim(coalesce(v_q.correct_answer,'')))
      or public.iclub_normalize_answer(v_selected) = public.iclub_normalize_answer(v_q.correct_answer)
    );

    select d.* into v_diag
    from public.question_answer_diagnostics d
    where d.question_id = p_question_id
      and d.answer_kind = 'mcq_option'
      and upper(trim(coalesce(d.answer_key,d.answer_value,''))) = upper(trim(coalesce(v_selected,'')))
      and d.quality_status = 'published'
    order by d.is_correct desc, d.id
    limit 1;
  else
    v_selected := trim(coalesce(p_user_answer,''));
    v_selected_norm := public.iclub_normalize_answer(v_selected);

    v_is_correct := exists (
      select 1
      from regexp_split_to_table(coalesce(v_q.correct_answer,''), '\|') as accepted_answer
      where public.iclub_normalize_answer(accepted_answer) = v_selected_norm
    );

    if not v_is_correct
       and public.iclub_is_numeric(v_selected)
       and public.iclub_is_numeric(v_q.correct_answer) then
      v_is_correct := replace(v_selected,',','.')::numeric = replace(v_q.correct_answer,',','.')::numeric;
    end if;

    select d.* into v_diag
    from public.question_answer_diagnostics d
    where d.question_id = p_question_id
      and d.answer_kind = 'input_exact'
      and d.quality_status = 'published'
      and (
        public.iclub_normalize_answer(coalesce(d.answer_value,d.answer_key,'')) = v_selected_norm
        or d.is_correct = v_is_correct
      )
    order by d.is_correct desc, d.id
    limit 1;

    if v_diag.id is null and public.iclub_is_numeric(v_selected) then
      select d.* into v_diag
      from public.question_answer_diagnostics d
      where d.question_id = p_question_id
        and d.answer_kind = 'input_tolerance'
        and d.quality_status = 'published'
        and coalesce(d.rule_json->>'target','') ~ '^-?[0-9]+([\.,][0-9]+)?$'
        and coalesce(d.rule_json->>'tolerance','') ~ '^[0-9]+([\.,][0-9]+)?$'
        and abs(replace(v_selected,',','.')::numeric - replace(d.rule_json->>'target',',','.')::numeric)
            <= replace(d.rule_json->>'tolerance',',','.')::numeric
      order by d.is_correct desc, d.id
      limit 1;
    end if;

    if v_diag.id is null then
      select d.* into v_diag
      from public.question_answer_diagnostics d
      where d.question_id = p_question_id
        and d.answer_kind = 'input_pattern'
        and d.quality_status = 'published'
        and d.answer_value is not null
        and v_selected ~* d.answer_value
      order by d.is_correct desc, d.id
      limit 1;
    end if;
  end if;

  if v_diag.id is null then
    select d.* into v_diag
    from public.question_answer_diagnostics d
    where d.question_id = p_question_id
      and d.answer_kind = 'fallback'
      and d.quality_status = 'published'
    order by d.is_correct desc, d.id
    limit 1;
  end if;

  return jsonb_build_object(
    'selected_answer', nullif(v_selected,''),
    'is_correct', v_is_correct,
    'diagnostic_id', v_diag.id,
    'mistake_type', v_diag.mistake_type,
    'weak_skill', v_diag.weak_skill,
    'feedback_ru', v_diag.feedback_ru,
    'feedback_uz', v_diag.feedback_uz,
    'feedback_en', v_diag.feedback_en,
    'next_action_ru', v_diag.next_action_ru,
    'next_action_uz', v_diag.next_action_uz,
    'next_action_en', v_diag.next_action_en
  );
end;
$$;

create or replace function public.iclub_tour_eval_v2(
  p_question_id bigint,
  p_user_answer text,
  p_picked_index integer,
  p_answered boolean
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_q public.questions%rowtype;
  v_selected text;
  v_is_correct boolean := false;
begin
  select q.* into v_q
  from public.questions q
  where q.id = p_question_id
    and q.is_active is true;

  if v_q.id is null then
    raise exception 'question_not_found_or_inactive' using errcode = 'P0002';
  end if;

  if coalesce(p_answered,true) is false then
    return jsonb_build_object('selected_answer', null, 'is_correct', false);
  end if;

  if lower(coalesce(v_q.qtype,'')) = 'mcq' then
    if p_picked_index is not null and p_picked_index between 0 and 25 then
      v_selected := chr(65 + p_picked_index);
    elsif upper(trim(coalesce(p_user_answer,''))) ~ '^[A-Z]$' then
      v_selected := upper(trim(p_user_answer));
    elsif trim(coalesce(p_user_answer,'')) ~ '^[0-9]+$'
      and trim(p_user_answer)::integer between 0 and 25 then
      v_selected := chr(65 + trim(p_user_answer)::integer);
    else
      v_selected := upper(trim(coalesce(p_user_answer,'')));
    end if;

    v_is_correct := upper(trim(coalesce(v_selected,''))) = upper(trim(coalesce(v_q.correct_answer,'')));
  else
    v_selected := trim(coalesce(p_user_answer,''));
    v_is_correct := public.iclub_tour_input_is_correct_v2(v_selected, v_q.correct_answer);
  end if;

  return jsonb_build_object('selected_answer', nullif(v_selected,''), 'is_correct', v_is_correct);
end;
$$;

