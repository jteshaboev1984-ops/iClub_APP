create or replace function public.start_practice_session_safe_v2(
  p_pool_id bigint,
  p_client_session_id text,
  p_question_ids bigint[] default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_pool public.practice_pools%rowtype;
  v_session public.practice_sessions_v2%rowtype;
  v_qids bigint[];
  v_total integer;
  v_allowed integer;
begin
  if v_uid is null then
    raise exception 'not_authenticated' using errcode = '28000';
  end if;
  if p_pool_id is null or p_pool_id <= 0 then
    raise exception 'invalid_pool_id' using errcode = '22023';
  end if;
  if p_client_session_id is null or length(trim(p_client_session_id)) not between 8 and 128 then
    raise exception 'invalid_client_session_id' using errcode = '22023';
  end if;

  select * into v_session
  from public.practice_sessions_v2 s
  where s.user_id = v_uid and s.client_session_id = trim(p_client_session_id)
  limit 1;

  if v_session.id is not null then
    return jsonb_build_object(
      'session_id', v_session.id,
      'status', v_session.status,
      'question_count', cardinality(v_session.question_ids),
      'legacy_attempt_id', v_session.legacy_attempt_id,
      'resumed', true
    );
  end if;

  select * into v_pool
  from public.practice_pools p
  where p.id = p_pool_id and p.is_active is true;

  if v_pool.id is null then
    raise exception 'pool_not_found_or_inactive' using errcode = 'P0002';
  end if;

  if p_question_ids is null or cardinality(p_question_ids) = 0 then
    select array_agg(ppq.question_id order by ppq.order_no, ppq.id)
      into v_qids
    from public.practice_pool_questions ppq
    join public.questions q on q.id = ppq.question_id and q.is_active is true
    where ppq.pool_id = p_pool_id and ppq.is_active is true;
  else
    select array_agg(x.qid order by x.ord)
      into v_qids
    from unnest(p_question_ids) with ordinality as x(qid,ord)
    where x.qid is not null;
  end if;

  v_total := coalesce(cardinality(v_qids),0);
  if v_total < 1 or v_total > 200 then
    raise exception 'invalid_question_count' using errcode = '22023';
  end if;

  if (select count(distinct x) from unnest(v_qids) x) <> v_total then
    raise exception 'duplicate_question_ids' using errcode = '22023';
  end if;

  select count(*)::integer into v_allowed
  from public.practice_pool_questions ppq
  join public.questions q on q.id = ppq.question_id
  where ppq.pool_id = p_pool_id
    and ppq.is_active is true
    and q.is_active is true
    and q.subject_id = v_pool.subject_id
    and ppq.question_id = any(v_qids);

  if v_allowed <> v_total then
    raise exception 'question_not_in_active_pool' using errcode = '22023';
  end if;

  insert into public.practice_sessions_v2(
    user_id, subject_id, pool_id, client_session_id, question_ids
  ) values (
    v_uid, v_pool.subject_id, p_pool_id, trim(p_client_session_id), v_qids
  ) returning * into v_session;

  return jsonb_build_object(
    'session_id', v_session.id,
    'status', v_session.status,
    'question_count', v_total,
    'legacy_attempt_id', null,
    'resumed', false
  );
exception
  when unique_violation then
    select * into v_session
    from public.practice_sessions_v2 s
    where s.user_id = v_uid and s.client_session_id = trim(p_client_session_id)
    limit 1;
    if v_session.id is null then raise; end if;
    return jsonb_build_object(
      'session_id', v_session.id,
      'status', v_session.status,
      'question_count', cardinality(v_session.question_ids),
      'legacy_attempt_id', v_session.legacy_attempt_id,
      'resumed', true
    );
end;
$$;

