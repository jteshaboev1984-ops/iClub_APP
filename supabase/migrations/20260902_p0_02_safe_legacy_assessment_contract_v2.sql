-- iClub APP — P0-02 safe legacy assessment contract v2
-- Branch-only design migration. DO NOT apply to production until P0-02 gate approval.
--
-- Goals:
--   1) keep pre-answer question payloads free of correct_answer/explanations;
--   2) move Practice/Tour correctness to SECURITY DEFINER server RPCs;
--   3) preserve legacy completed Practice/Tour rows and one-attempt Tour semantics;
--   4) keep current questions_public_read and legacy policies untouched until regression passes;
--   5) make all new session/runtime tables private to direct anon/auth access.
--
-- This migration is additive. It contains no UPDATE/DELETE/TRUNCATE of historical rows,
-- no rewrite of question IDs, no RLS cutover, and no feature enable.

begin;

-- =========================================================
-- 1. Private runtime/session tables
-- =========================================================

create table if not exists public.practice_sessions_v2 (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  subject_id bigint not null references public.subjects(id),
  pool_id bigint not null references public.practice_pools(id),
  client_session_id text not null,
  question_ids bigint[] not null,
  legacy_attempt_id bigint unique references public.practice_attempts(id),
  status text not null default 'in_progress'
    check (status in ('in_progress','finalized','abandoned')),
  created_at timestamptz not null default now(),
  finalized_at timestamptz,
  unique (user_id, client_session_id),
  check (cardinality(question_ids) between 1 and 200),
  check (length(client_session_id) between 8 and 128)
);

create table if not exists public.practice_session_answers_v2 (
  session_id bigint not null references public.practice_sessions_v2(id) on delete cascade,
  question_id bigint not null references public.questions(id),
  selected_answer text,
  picked_index integer,
  is_correct boolean not null,
  time_spent integer not null default 0 check (time_spent >= 0),
  diagnostic_id bigint references public.question_answer_diagnostics(id),
  mistake_type text,
  weak_skill text,
  feedback_ru text,
  feedback_uz text,
  feedback_en text,
  next_action_ru text,
  next_action_uz text,
  next_action_en text,
  answered_at timestamptz not null default now(),
  primary key (session_id, question_id)
);

create table if not exists public.tour_session_runtime_v2 (
  attempt_id bigint primary key references public.tour_attempts(id) on delete cascade,
  user_id uuid not null,
  tour_id bigint not null references public.tours(id),
  client_session_id text not null,
  question_ids bigint[] not null,
  finalized_at timestamptz,
  created_at timestamptz not null default now(),
  unique (user_id, client_session_id),
  unique (user_id, tour_id),
  check (cardinality(question_ids) between 1 and 100),
  check (length(client_session_id) between 8 and 128)
);

create table if not exists public.tour_session_answers_v2 (
  attempt_id bigint not null references public.tour_session_runtime_v2(attempt_id) on delete cascade,
  question_id bigint not null references public.questions(id),
  user_answer text,
  answered boolean not null default true,
  is_correct boolean not null default false,
  time_spent integer not null default 0 check (time_spent >= 0),
  finish_reason text,
  answered_at timestamptz not null default now(),
  primary key (attempt_id, question_id)
);

alter table public.practice_sessions_v2 enable row level security;
alter table public.practice_session_answers_v2 enable row level security;
alter table public.tour_session_runtime_v2 enable row level security;
alter table public.tour_session_answers_v2 enable row level security;

-- Runtime tables are intentionally inaccessible directly from browser roles.
revoke all on table public.practice_sessions_v2 from public, anon, authenticated;
revoke all on table public.practice_session_answers_v2 from public, anon, authenticated;
revoke all on table public.tour_session_runtime_v2 from public, anon, authenticated;
revoke all on table public.tour_session_answers_v2 from public, anon, authenticated;
revoke all on sequence public.practice_sessions_v2_id_seq from public, anon, authenticated;

