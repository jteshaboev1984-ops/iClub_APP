create or replace function public.submit_tour_answer_safe_v2(
  p_attempt_id bigint,
  p_question_id bigint,
  p_user_answer text,
  p_picked_index integer,
  p_time_spent integer,
  p_answered boolean default true,
  p_finish_reason text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_rt public.tour_session_runtime_v2%rowtype;
  v_eval jsonb;
  v_answered_count integer;
begin
  if v_uid is null then
    raise exception 'not_authenticated' using errcode='28000';
  end if;

  select * into v_rt from public.tour_session_runtime_v2 r
  where r.attempt_id=p_attempt_id and r.user_id=v_uid;
  if v_rt.attempt_id is null then
    raise exception 'tour_session_not_found' using errcode='P0002';
  end if;
  if v_rt.finalized_at is not null then
    raise exception 'tour_session_finalized' using errcode='55000';
  end if;
  if not (p_question_id = any(v_rt.question_ids)) then
    raise exception 'question_not_in_tour_session' using errcode='22023';
  end if;

  v_eval := public.iclub_tour_eval_v2(
    p_question_id,p_user_answer,p_picked_index,coalesce(p_answered,true)
  );

  insert into public.tour_session_answers_v2(
    attempt_id,question_id,user_answer,answered,is_correct,time_spent,finish_reason,answered_at
  ) values (
    p_attempt_id,p_question_id,
    v_eval->>'selected_answer',coalesce(p_answered,true),
    coalesce((v_eval->>'is_correct')::boolean,false),
    greatest(coalesce(p_time_spent,0),0),nullif(trim(coalesce(p_finish_reason,'')),''),now()
  )
  on conflict (attempt_id,question_id) do update set
    user_answer=excluded.user_answer,
    answered=excluded.answered,
    is_correct=excluded.is_correct,
    time_spent=excluded.time_spent,
    finish_reason=excluded.finish_reason,
    answered_at=now();

  select count(*)::integer into v_answered_count
  from public.tour_session_answers_v2 a
  where a.attempt_id=p_attempt_id;

  -- Protected Tour response deliberately omits is_correct, correct_answer and explanation.
  return jsonb_build_object(
    'ok',true,
    'attempt_id',p_attempt_id,
    'question_id',p_question_id,
    'recorded',true,
    'recorded_count',v_answered_count,
    'question_count',cardinality(v_rt.question_ids)
  );
end;
$$;

create or replace function public.finalize_tour_attempt_safe_v2(
  p_attempt_id bigint,
  p_total_time integer,
  p_status text default 'submitted'
)
returns jsonb
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_rt public.tour_session_runtime_v2%rowtype;
  v_total integer;
  v_score integer;
  v_percent numeric;
  v_status text := lower(trim(coalesce(p_status,'submitted')));
begin
  if v_uid is null then
    raise exception 'not_authenticated' using errcode='28000';
  end if;
  if v_status not in ('submitted','time_expired','anti_cheat','abandoned') then
    raise exception 'invalid_tour_status' using errcode='22023';
  end if;

  select * into v_rt from public.tour_session_runtime_v2 r
  where r.attempt_id=p_attempt_id and r.user_id=v_uid
  for update;
  if v_rt.attempt_id is null then
    raise exception 'tour_session_not_found' using errcode='P0002';
  end if;

  if v_rt.finalized_at is not null then
    select a.score,a.percent into v_score,v_percent
    from public.tour_attempts a where a.id=p_attempt_id and a.user_id=v_uid;
    return jsonb_build_object(
      'ok',true,'attempt_id',p_attempt_id,
      'score',coalesce(v_score,0),'percent',coalesce(v_percent,0),
      'question_count',cardinality(v_rt.question_ids),'status',v_status,'idempotent',true
    );
  end if;

  v_total := cardinality(v_rt.question_ids);

  -- Persist an explicit unanswered row for every omitted question at finalization.
  insert into public.tour_session_answers_v2(
    attempt_id,question_id,user_answer,answered,is_correct,time_spent,finish_reason
  )
  select p_attempt_id,x.qid,null,false,false,0,v_status
  from unnest(v_rt.question_ids) x(qid)
  where not exists (
    select 1 from public.tour_session_answers_v2 a
    where a.attempt_id=p_attempt_id and a.question_id=x.qid
  )
  on conflict do nothing;

  select count(*) filter (where a.is_correct is true)::integer
    into v_score
  from public.tour_session_answers_v2 a
  where a.attempt_id=p_attempt_id and a.question_id=any(v_rt.question_ids);

  v_percent := case when v_total > 0
    then round((v_score::numeric / v_total::numeric) * 100,2)
    else 0 end;

  insert into public.tour_answers(
    attempt_id,question_id,user_answer,answered,is_correct,time_spent,finish_reason
  )
  select a.attempt_id,a.question_id,a.user_answer,a.answered,a.is_correct,a.time_spent,a.finish_reason
  from public.tour_session_answers_v2 a
  where a.attempt_id=p_attempt_id and a.question_id=any(v_rt.question_ids)
  on conflict (attempt_id,question_id) do update set
    user_answer=excluded.user_answer,
    answered=excluded.answered,
    is_correct=excluded.is_correct,
    time_spent=excluded.time_spent,
    finish_reason=excluded.finish_reason;

  update public.tour_attempts a
  set score=v_score,
      percent=v_percent,
      total_time=greatest(coalesce(p_total_time,0),0),
      status=v_status
  where a.id=p_attempt_id and a.user_id=v_uid and a.tour_id=v_rt.tour_id;

  if not found then
    raise exception 'tour_attempt_update_failed' using errcode='P0002';
  end if;

  update public.tour_session_runtime_v2
  set finalized_at=now()
  where attempt_id=p_attempt_id and user_id=v_uid;

  return jsonb_build_object(
    'ok',true,'attempt_id',p_attempt_id,
    'score',v_score,'percent',v_percent,
    'question_count',v_total,'status',v_status,'idempotent',false
  );
end;
$$;

