const switchSql=read("supabase/migrations/20261007007500_math_practice_v2_atomic_release_switch_v1.sql");
assert(index.includes("security/practice-v2-local-reset.js?v=stage03oldhistory2"),"Old eager reset may remain cached");
assert(app.includes("await window.iclubMathPracticeV2ResetAfterPublish?.(window.sb)"),"Boot not gated after server proof");
assert(!app.includes("if (cleared === true) state = loadState()"),"Legacy cleanup must not reload active Practice");
assert(reset.includes("result?.data !== true")&&reset.includes("is_math_practice_v2_published_safe_v1"),"Reset does not require true authenticated publish proof");
assert(!reset.includes('PRACTICE_HISTORY_PREFIXES'),"Reset may erase fresh Practice history v3");
assert(reset.includes('LEGACY_PREFIX = "practice_history_v2:mathematics:tour_"'),"Wrong legacy Practice namespace");
assert(gate.includes("auth.uid() is null")&&gate.includes("a.status = 'published'")&&gate.includes("count(*) = 495"),"Publication gate insufficient");
assert(/revoke all on function public.is_math_practice_v2_published_safe_v1\(\) from public, anon/.test(gate),"Anonymous call privilege not revoked");
assert(!/\b(delete\s+from|truncate|insert\s+into|update\s+(public|private)\.)\b/i.test(gate),"Publication proof migration writes user data");
assert(select.includes("choose_iclub_my_free_subject_v2"),"Free atomic subject selector missing");
assert(access.includes("window.addEventListener(\"iclub:subject-selection-changed\", () => {")&&access.includes("    invalidate();"),"Old subject cache not invalidated");
assert(preview.includes("window.__iclubRegistrationPreview"),"Registration preview not present");
assert(!/\b(window\.sb|supabase|localStorage|sessionStorage|fetch\s*\()\b/.test(preview),"Preview could access actual learner data");
assert(qa.includes("passed===72"),"RU/UZ/EN screen/mobile preview matrix incomplete");
assert(switchSql.includes("private.practice_v2_tour_invariant_snapshot_v1"),"Atomic publish lacks protected Tour fingerprint");
assert(switchSql.includes("raise exception 'protected_tour_invariant_changed_during_release'"),"Tour mutation would not abort publish");
assert(plan.includes("pre-publish local cleanup is prohibited"),"Legacy release instructions still clear local state early");
assert(docs.toLowerCase().includes("rollback")&&docs.toLowerCase().includes("production")&&docs.includes("NO-GO"),"Clean release rollback/STOP gates are missing");
console.log("iClub unified release static STOP gates GREEN (no deployment, bank mutation or learner data used).");
