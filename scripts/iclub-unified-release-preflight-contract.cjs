#!/usr/bin/env node
"use strict";
const fs=require("node:fs");
const path=require("node:path");
const root=path.resolve(__dirname,"..");
const read=(p)=>fs.readFileSync(path.join(root,p),"utf8");
const assert=(ok,what)=>{if(!ok)throw Error(what)};
const docs=read("docs/iclub-clean-release-v3-20261009.md");
const plan=read("docs/mathematics-practice-v2-controlled-release-runbook.md");
const index=read("index.html");
const app=read("app.js");
const reset=read("security/practice-v2-local-reset.js");
const gate=read("supabase/migrations/20261008110000_math_practice_v2_post_publish_local_reset_gate_v1.sql");
